export function getMissionsForTier(tierRank: number): MissionDefinition[] {
  return NFS_MISSIONS.filter((m) => m.tierRank === tierRank).sort((a, b) => a.order - b.order);
}

export function getTierMissionProgress(tierRank: number, completedMissionIds: string[]) {
  const missions = getMissionsForTier(tierRank);
  const completed = missions.filter((m) => completedMissionIds.includes(m.id)).length;
  return {
    completed,
    total: missions.length,
    allDone: missions.length > 0 && completed >= missions.length,
  };
}

export function isTierBossUnlocked(rival: BlacklistRival, profile: CareerProfile) {
  const rankCleared = profile.blacklistDefeated;
  const expectedMinCleared = 10 - rival.rank; // #10 => 0, #9 => 1, ... #1 => 9
  const rankReached = rankCleared >= expectedMinCleared;
  const missionState = getTierMissionProgress(rival.rank, profile.completedMissionIds || []);
  const bountyMet = profile.totalBounty >= rival.requiredBounty;
  const takedownsMet = profile.copsTakedowns >= rival.requiredTakedowns;
  return {
    unlocked: rankReached && missionState.allDone && bountyMet && takedownsMet,
    rankReached,
    missionsDone: missionState.completed,
    missionsTotal: missionState.total,
    allMissionsDone: missionState.allDone,
    bountyMet,
    takedownsMet,
  };
}

