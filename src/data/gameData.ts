export function computeEffectiveStats(spec: CarSpec, cfg: GarageCarConfig) {
  const topSpeedKmh = Math.round(
    spec.baseTopSpeedKmh + (cfg.engineLevel - 1) * 14 + (cfg.turboLevel - 1) * 9,
  );
  const accel = Math.min(
    100,
    Math.round(spec.baseAccel + (cfg.engineLevel - 1) * 4 + (cfg.turboLevel - 1) * 6),
  );
  const handling = Math.min(
    100,
    Math.round(spec.baseHandling + (cfg.tiresLevel - 1) * 6),
  );
  const nitrous = Math.min(
    100,
    Math.round(spec.baseNitrous + (cfg.nitrousLevel - 1) * 7),
  );
  return { topSpeedKmh, accel, handling, nitrous };
}

export function formatTimeMs(ms: number): string {
  if (!ms || ms <= 0) return '--:--.--';
  const totalSec = ms / 1000;
  const mins = Math.floor(totalSec / 60);
  const secs = Math.floor(totalSec % 60);
  const hundredths = Math.floor((ms % 1000) / 10);
  return `${String(mins).padStart(2, '0')}:${String(secs).padStart(2, '0')}.${String(hundredths).padStart(2, '0')}`;
}

export function formatCurrency(amount: number): string {
  return `$${Math.max(0, Math.round(amount)).toLocaleString('en-US')}`;
}
