export function resolveMissionRaceMode(type: MissionDefinition['type']): 'circuit' | 'sprint' | 'knockout' | 'tollbooth' | 'speedtrap' | 'pursuit' {
  switch (type) {
    case 'pursuit_milestone':
    case 'interceptor':
      return 'pursuit';
    case 'sprint':
      return 'sprint';
    case 'knockout':
      return 'knockout';
    case 'tollbooth':
      return 'tollbooth';
    case 'speedtrap':
      return 'speedtrap';
    case 'shortcut_heist':
    case 'drift_showdown':
    case 'stunt_blitz':
    case 'circuit':
    default:
      return 'circuit';
  }
}

